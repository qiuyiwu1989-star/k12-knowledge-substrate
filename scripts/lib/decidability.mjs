/** 断言里出现即拒绝的模糊头词（它们属于 literacy 标签，不属于 statement） */
const VAGUE_HEADS = [
  '能力', '素养', '意识', '精神', '观念', '态度', '兴趣', '习惯', '思想', '情感', '品格', '价值观',
];

/** 「养成…习惯」和「形成…意识」是同一类口号，都不可判定 */
const SLOGAN_VERBS = ['培养', '提高', '增强', '树立', '形成', '激发', '发展', '养成', '具有', '具备', '提升'];

/** 章节名 / 内容主题的典型尾缀 */
const CHAPTER_TAILS = ['的意义', '的概念', '的认识', '的理解', '的性质', '的应用', '的特点', '的分类', '简介', '初步认识'];

/** 无判定条件的虚动词（单独出现即拒绝） */
const WEAK_VERBS = ['了解', '知道', '认识', '感受', '体会', '体验', '欣赏', '培养', '树立', '形成', '增强', '提高', '激发'];

/**
 * @returns {{ok: boolean, verb: string|null, reasons: string[]}}
 */
export function checkDecidable(statement) {
  const reasons = [];
  const s = String(statement ?? '').trim();

  if (s.length < 8) reasons.push('过短：不足 8 字，几乎不可能包含判定条件');
  if (s.length > 60) reasons.push('过长：超过 60 字，多半是把几条能力揉在了一起，应拆分');

  // 1) 必须命中一个可观察行为动词（取最长匹配）
  let verb = null;
  for (const v of ACTION_VERBS) {
    if (s.includes(v) && (!verb || v.length > verb.length)) verb = v;
  }
  // 课标爱用单字动词顿号并列：「能认、读、写万以内的数」「会读、写、比、算」。
  // 单字动词单独放进词表误报太高，只在「能/会 + 单字动词 + 顿号」这个格式里认。
  if (!verb) {
    const m = s.match(/[能会](?:[认读写画量摆拼剪贴算说数比排分][、,，])+[认读写画量摆拼剪贴算说数比排分]/);
    if (m) verb = m[0].slice(1).split(/[、,，]/)[0];
  }
  if (!verb) {
    reasons.push('无可观察行为动词：改写成「能<动词><对象>」的形式，动词须来自 ACTION_VERBS');
  }

  // 2) 纯名词短语 / 章节名
  for (const t of CHAPTER_TAILS) {
    if (s.endsWith(t)) reasons.push(`章节名而非能力：以「${t}」结尾`);
  }

  // 3) 模糊头词。只有在「没有实动词」时才算致命 —— 泛称作为实动词的宾语是允许的：
  //    ❌ 培养观察能力（无动词，泛称是被培养的对象）
  //    ✅ 能说出明月这一意象常关联的情感（有动词，泛称是可被说出的东西）
  if (!verb) {
    for (const h of VAGUE_HEADS) {
      if (s.includes(h)) reasons.push(`含能力泛称「${h}」且无可观察动词：它属于 literacy 标签字段，不属于 statement`);
    }
  }
  // 「培养/提高 + 泛称」无论有没有动词都拒绝 —— 这是课标口号句式，永远不可判定
  const slogan = s.match(new RegExp(`(${SLOGAN_VERBS.join('|')})[^，。]{0,10}(${VAGUE_HEADS.join('|')})`));
  if (slogan) reasons.push(`口号句式「${slogan[0]}」不可判定：改写成一次可观察的行为`);

  // 4a) 以虚动词开头 = 整句是认知态度描述，句中偶然出现的实义动词只是宾语的一部分。
  //     实测：「懂得比赛中的互相保护与行为礼仪」因「保护」进了词表而误放，
  //     它描述的是「懂得」，不是「保护」这个可观察动作。
  const leadWeak = s.match(/^[^，。；]{0,4}?(懂得|知道|了解|认识到|认识|体会|感受|意识到|明白)/);
  if (leadWeak) {
    reasons.push(`以认知动词「${leadWeak[1]}」起句：整句描述的是「知道什么」而非「能做什么」，改写成可观察行为`);
  }

  // 4b) 只有虚动词、没有实动词
  if (!verb) {
    for (const w of WEAK_VERBS) {
      if (s.includes(w)) {
        reasons.push(`虚动词「${w}」不可判定：改成可观察的行为（如「能说出…」「能举例说明…」）`);
        break;
      }
    }
  }

  // 5) 必须有作用对象——动词后面得跟着东西
  if (verb) {
    const after = s.slice(s.indexOf(verb) + verb.length).replace(/[，。、；：？！\s]/g, '');
    if (after.length < 2) reasons.push('动词后无作用对象：说清「对什么」做这个动作');
  }

  // 6) 悬空指代。课标原文是「认识长方形、正方形…能直观描述这些平面图形的特征」，
  //    在逗号处切开后「这些」就没了指代对象 —— 脱离上下文根本判断不了指什么。
  //    这是切分留下的伤，不是原文的问题，但留在库里就是一条不可判定的锚点。
  const dangling = s.match(/(这些|这类|这几|上述|该类|其中的|此类)/);
  if (dangling && !/(这些|这类|这几|上述|该类|其中的|此类)[^，。]{0,4}(的)?[一二三四五六七八九十百千万\d]/.test(s)) {
    reasons.push(`悬空指代「${dangling[0]}」：脱离上下文无法判断指什么，需把指代对象写进断言`);
  }

  // 7) 真谓语是虚动词。「能在解决问题的过程中，体会解决问题的道理」——
  //    「解决」在动词表里所以过了闸，但句子真正要求的是「体会」。
  //    判据：末尾那个动词才是谓语。
  const tailWeak = s.match(new RegExp(`(${WEAK_VERBS.join('|')})[^，。；]{0,12}$`));
  if (tailWeak && verb && s.indexOf(verb) < s.indexOf(tailWeak[1])) {
    reasons.push(`句末谓语是虚动词「${tailWeak[1]}」：前面的「${verb}」只是状语里的动作，真正要求的仍不可判定`);
  }

  // 8) 顿号堆叠 = 一条锚点塞了多条能力
  const commas = (s.match(/[、，]/g) || []).length;
  if (commas >= 3) reasons.push('并列项过多（≥3 个顿号）：一个锚点只承载一条可判定能力，请拆分');

  return { ok: reasons.length === 0, verb, reasons };
}

/** 自测用例——`node scripts/lib/decidability.mjs` 直接跑 */
export const FIXTURES = {
  reject: [
    '分数的意义',
    '培养学生的观察能力',
    '了解古代中国的政治制度',
    '认识钟表',
    '感受诗歌的意境美',
    '掌握两位数加法',
    '形成初步的数感和符号意识',
    '感悟数学与现实世界的关联',
    '万以内数的认识',
    '能说出、写出、读出、认读常用汉字并组词造句',
  ],
  accept: [
    '能把 3/4 标在 0 到 1 的数轴上并说明理由',
    '能默写《静夜思》全诗且无错别字',
    '能举例说明「举头」与「低头」的动作对比表达了什么情绪',
    '能比较两个同分母分数的大小并说明依据',
    '能计算两位数加两位数的进位加法',
    // ↓ 2022 课标【学业要求】原文。先验词表曾把这几条全判死，
    //   是在数学课标试跑时才发现的 —— 别再改回去。
    '能认、读、写万以内的数',
    '能熟练口算20以内数的加减法和表内乘除法',
    '能计算两位数和三位数的加减法',
    '能说出不同数位上的数表示的数值',
    '能描述四则运算的含义',
    '能根据具体问题中的数量关系列出方程',
    '能连接简单的串联电路和并联电路',
    '能参照范例仿写简单句',
    '能与同伴相互保护和帮助',
  ],
};

if (import.meta.url === `file://${process.argv[1]}`) {
  let bad = 0;
  for (const s of FIXTURES.reject) {
    const r = checkDecidable(s);
    if (r.ok) { console.error(`✗ 漏放（应拒绝）: ${s}`); bad++; }
    else console.log(`✓ 拒绝 "${s}"\n    ${r.reasons.join('\n    ')}`);
  }
  for (const s of FIXTURES.accept) {
    const r = checkDecidable(s);
    if (!r.ok) { console.error(`✗ 误杀（应通过）: ${s}\n    ${r.reasons.join('\n    ')}`); bad++; }
    else console.log(`✓ 通过 "${s}"  [verb=${r.verb}]`);
  }
  console.log(bad ? `\n✗ ${bad} 个用例不符` : '\n✓ 过滤器自测全部通过');
  process.exit(bad ? 1 : 0);
}
