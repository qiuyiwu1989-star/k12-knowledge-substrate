    '万以内数的认识',
    '能说出、写出、读出、认读常用汉字并组词造句',
    // ↓ 历史/地理/道法课标的【内容要求】原文。放开「知道+判断命题」那条时，
    //   必须保证这类**主题式**要求仍然被拒 —— 它们没有可问的标准答案。
    '知道中国境内原始社会时期的人类活动',
