/**
 * decidability.mjs — 可判定性过滤器。全线最有价值的一道闸。
 *
 * 判据只有一个：能不能对一个具体孩子在某一时刻回答『会 / 不会 / 多大程度』。
 *
 *   ❌ 分数的意义        → 章节名，不可判定
 *   ❌ 培养观察能力      → 能力泛称，不可判定
 *   ✅ 能把 3/4 标在数轴上并说明为什么在那
 *
 * 这道闸能砍掉 LLM 批量抽取输出的 60–70%，而且全自动。
 * 它是把「知识点图谱」变成「档案坐标系」的那道工序 —— 没有它，
 * 做出来的就是市面上又一个用来打标推题的图谱，挂不了档案。
 */

