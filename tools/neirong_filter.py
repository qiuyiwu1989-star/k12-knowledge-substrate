#!/usr/bin/env python3
"""关于课标文件本身的话，不是学生能力 —— 抽取时会混进来，这里再拦一道。

「能说出历史课程内容包括七个板块」是在描述这份文件的编排，不是历史知识。
模型在 prompt 里被告知过要跳过，但它会漏；prompt 是软约束，这里是硬闸。
"""
import re
META = re.compile(
    r'(本?课程内容|本课程|课程标准|本标准|课程目标|本学段设置|教学中|教学应|'
    r'教材编写|评价建议|学业质量标准|课时|板块|学习主题|课程的?主要线索|'
    r'义务教育课程|占总课时|学段目标|课程性质|课程理念|教学提示|学业要求是|'
    # ↓ 目录页与前言页的残渣。页码范围给错时会成批混进来 ——
    #   实测劳动课标按错误页码抽，抽出了「课程资源开发与利用建议的页码是57」。
    r'页码是|………|根本遵循|重要论述|修订|指导思想|附录\d)')

# 「能说出 + 主题」不是能力。把「知道X」改写成「能说出X」时，等于亲手给
# 主题式要求配了个动词，可判定性闸就被绕过去了 —— 闸原本正是靠「没有实义
# 动词」拦住它们的。所以改写后必须再上一次同样的判据：句子得是**有标准答案
# 的命题**，不能只是个话题。
PROPOSITION = re.compile(r'[^，。；]{2,}是[^，。；]{2,}|《[^》]+》|\d')
TOPIC_TAIL = re.compile(
    r'(的?基本常识和?要求|的?常识|的?知识|的?内容|的?要求|的?方法|的?过程|'
    r'的?特点|的?意义|的?作用|的?影响|的?关系|的?表现|的?途径|的?措施)$')


def is_meta(stmt):
    return bool(META.search(stmt))


def is_proposition(stmt):
    """改写后的断言是否落到了一个可问出标准答案的命题上"""
    if TOPIC_TAIL.search(stmt):
        return False
    return bool(PROPOSITION.search(stmt))
